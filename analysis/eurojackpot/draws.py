def validate():
    """Structural checks on the transcription. Raises on any problem."""
    seen = set()
    prev = ""
    for d, mains, euros in DRAWS:
        assert d > prev, f"dates out of order at {d}"
        assert d not in seen, f"duplicate date {d}"
        seen.add(d)
        prev = d
        assert len(mains) == 5 and len(set(mains)) == 5, f"{d}: bad main set"
        assert all(1 <= n <= 50 for n in mains), f"{d}: main out of range"
        assert list(mains) == sorted(mains), f"{d}: mains not sorted"
        assert len(euros) == 2 and len(set(euros)) == 2, f"{d}: bad euro set"
        assert list(euros) == sorted(euros), f"{d}: euros not sorted"
        hi = 12 if d >= EURO_FORMAT_CHANGE else 10
        assert all(1 <= n <= hi for n in euros), f"{d}: euro out of range for format"
    return len(DRAWS)


def euro_draws():
    """Only draws under the current 2-from-12 euro format."""
    return [d for d in DRAWS if d[0] >= EURO_FORMAT_CHANGE]


