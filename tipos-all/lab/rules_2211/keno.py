    evp=sum(P[h]*(h/20*B[k].get(h,0)+(1-h/20)*A[k].get(h,0)) for h in range(k+1))/2
    print(f'{k:2d} picks: EV {ev:.4f}  P(any) {pany:.4f}  P(>stake) {pprof:.4f} | KENO PLUS EV {evp:.4f}')
